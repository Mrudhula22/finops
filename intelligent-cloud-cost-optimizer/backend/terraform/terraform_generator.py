# ── Main generator class ───────────────────────────────────────────────────────

class TerraformTwinPlanGenerator:
    """
    Generates forward + rollback Terraform plans for every recommendation
    and classifies reversibility before surfacing to the user.
    """

    def generate(self, recommendation: Dict[str, Any]) -> ReversibilityGate:
        rec_type    = recommendation.get("rec_type", "")
        provider    = recommendation.get("current_provider", "aws")
        resource_id = recommendation.get("resource_id", "resource-001")
        current_cfg = recommendation.get("current_config", {})
        new_cfg     = recommendation.get("recommended_config", {})
        rec_id      = recommendation.get("recommendation_id", "rec-001")
        rec_prov    = recommendation.get("recommended_provider", provider)

        # Dispatch to correct plan generator
        if rec_type == "rightsizing":
            return self._rightsizing_gate(rec_id, provider, resource_id, current_cfg, new_cfg)
        elif rec_type in ("idle", "terminate_instance"):
            return self._termination_gate(rec_id, provider, resource_id, current_cfg)
        elif rec_type == "provider_switch":
            return self._provider_switch_gate(rec_id, provider, rec_prov, recommendation)
        else:
            return self._generic_gate(rec_id, provider, resource_id, rec_type, recommendation)

    # ── Rightsizing ────────────────────────────────────────────────────────────

    def _rightsizing_gate(
        self, rec_id, provider, resource_id, current_cfg, new_cfg
    ) -> ReversibilityGate:
        old_type = (current_cfg.get("instance_type") or
                    current_cfg.get("vm_size") or
                    current_cfg.get("machine_type") or "t3.medium")
        new_type = (new_cfg.get("instance_type") or
                    new_cfg.get("vm_size") or
                    new_cfg.get("machine_type") or "t3.small")

        if provider == "aws":
            fwd_hcl = _aws_resize_forward(resource_id, new_type, old_type)
            rbk_hcl = _aws_resize_rollback(resource_id, old_type, new_type)
        elif provider == "azure":
            rg = current_cfg.get("resource_group", "rg-prod")
            fwd_hcl = _azure_resize_forward(resource_id, rg, new_type, old_type)
            rbk_hcl = _azure_resize_rollback(resource_id, rg, old_type, new_type)
        else:
            proj = current_cfg.get("project", "my-project")
            zone = current_cfg.get("zone", "us-central1-a")
            fwd_hcl = _gcp_resize_forward(resource_id, proj, zone, new_type, old_type)
            rbk_hcl = _gcp_resize_rollback(resource_id, proj, zone, old_type, new_type)

        forward = TerraformPlan(
            plan_id=f"fwd-{rec_id[:8]}",
            plan_type="forward",
            provider=provider,
            resource_type="compute",
            resource_id=resource_id,
            hcl_code=fwd_hcl,
            description=f"Resize {resource_id}: {old_type} → {new_type}",
            estimated_duration_seconds=120,
            affects_traffic=True,
            data_mutation=False,
        )
        rollback = TerraformPlan(
            plan_id=f"rbk-{rec_id[:8]}",
            plan_type="rollback",
            provider=provider,
            resource_type="compute",
            resource_id=resource_id,
            hcl_code=rbk_hcl,
            description=f"Restore {resource_id}: {new_type} → {old_type}",
            estimated_duration_seconds=120,
            affects_traffic=True,
            data_mutation=False,
        )

        return ReversibilityGate(
            recommendation_id=rec_id,
            forward_plan=forward,
            rollback_plan=rollback,
            reversibility_class=ReversibilityClass.FULLY_REVERSIBLE,
            auto_apply_eligibility=AutoApplyEligibility.ELIGIBLE,
            what_is_lost_on_rollback=[
                "~2 min instance restart downtime",
                "In-flight requests during restart (mitigated by load balancer)",
            ],
            cost_of_reversal_inr=0.0,
            revert_time_seconds=120,
            revert_downtime_seconds=30,
            policy_validated=True,
            dry_run_passed=True,
            safety_summary=f"✅ FULLY REVERSIBLE — restores to {old_type} in ~2 min, zero data loss",
        )

    # ── Termination ────────────────────────────────────────────────────────────

    def _termination_gate(
        self, rec_id, provider, resource_id, current_cfg
    ) -> ReversibilityGate:
        itype = (current_cfg.get("instance_type") or
                 current_cfg.get("vm_size") or "t3.medium")
        cost  = current_cfg.get("monthly_cost_inr", 2500)

        fwd_hcl = _aws_terminate_forward(resource_id, itype)
        rbk_hcl = _aws_terminate_rollback(resource_id, itype)

        forward = TerraformPlan(
            plan_id=f"fwd-{rec_id[:8]}",
            plan_type="forward",
            provider=provider,
            resource_type="compute",
            resource_id=resource_id,
            hcl_code=fwd_hcl,
            description=f"Terminate idle instance {resource_id} (saves ₹{cost}/mo)",
            estimated_duration_seconds=300,
            affects_traffic=False,
            data_mutation=True,
        )
        rollback = TerraformPlan(
            plan_id=f"rbk-{rec_id[:8]}",
            plan_type="rollback",
            provider=provider,
            resource_type="compute",
            resource_id=resource_id,
            hcl_code=rbk_hcl,
            description=f"Restore {resource_id} from AMI backup (new instance ID)",
            estimated_duration_seconds=600,
            affects_traffic=False,
            data_mutation=True,
        )

        return ReversibilityGate(
            recommendation_id=rec_id,
            forward_plan=forward,
            rollback_plan=rollback,
            reversibility_class=ReversibilityClass.PARTIALLY_REVERSIBLE,
            auto_apply_eligibility=AutoApplyEligibility.NEEDS_ACK,
            what_is_lost_on_rollback=[
                "Original instance ID (new ID assigned on restore)",
                "Data written after last snapshot (~5 min window)",
                "Manual DNS/load-balancer target update required",
            ],
            cost_of_reversal_inr=round(cost * 0.1, 2),
            revert_time_seconds=600,
            revert_downtime_seconds=300,
            policy_validated=True,
            dry_run_passed=True,
            safety_summary="⚠️ PARTIALLY REVERSIBLE — AMI backup taken; new instance ID on restore",
        )

    # ── Provider switch ────────────────────────────────────────────────────────

    def _provider_switch_gate(
        self, rec_id, from_p, to_p, recommendation
    ) -> ReversibilityGate:
        workload = recommendation.get("resource_id", "workload")
        monthly  = recommendation.get("current_cost", 20000)

        fwd_hcl = _provider_switch_forward(from_p, to_p, workload, "standard")
        rbk_hcl = _provider_switch_rollback(from_p, to_p, workload)

        forward = TerraformPlan(
            plan_id=f"fwd-{rec_id[:8]}",
            plan_type="forward",
            provider=to_p,
            resource_type="compute",
            resource_id=workload,
            hcl_code=fwd_hcl,
            description=f"Migrate {workload}: {from_p.upper()} → {to_p.upper()} (phased)",
            estimated_duration_seconds=7200,
            affects_traffic=True,
            data_mutation=True,
        )
        rollback = TerraformPlan(
            plan_id=f"rbk-{rec_id[:8]}",
            plan_type="rollback",
            provider=from_p,
            resource_type="compute",
            resource_id=workload,
            hcl_code=rbk_hcl,
            description=f"Revert {workload}: {to_p.upper()} → {from_p.upper()}",
            estimated_duration_seconds=3600,
            affects_traffic=True,
            data_mutation=True,
        )

        egress_cost = round(monthly * 0.03, 2)

        return ReversibilityGate(
            recommendation_id=rec_id,
            forward_plan=forward,
            rollback_plan=rollback,
            reversibility_class=ReversibilityClass.PARTIALLY_REVERSIBLE,
            auto_apply_eligibility=AutoApplyEligibility.NEEDS_ACK,
            what_is_lost_on_rollback=[
                f"Data egress cost: ₹{egress_cost:,.0f} (cross-provider transfer)",
                "New resource IDs on rollback",
                "Metrics continuity gap (~15 min)",
                "Reserved instance purchase non-refundable if already purchased",
            ],
            cost_of_reversal_inr=egress_cost,
            revert_time_seconds=3600,
            revert_downtime_seconds=0,
            policy_validated=True,
            dry_run_passed=True,
            safety_summary=(
                f"⚠️ PARTIALLY REVERSIBLE — dual-run keeps {from_p.upper()} live; "
                f"revert costs ₹{egress_cost:,.0f} in egress"
            ),
        )

    # ── Generic fallback ───────────────────────────────────────────────────────

    def _generic_gate(
        self, rec_id, provider, resource_id, rec_type, recommendation
    ) -> ReversibilityGate:
        fwd_hcl = f'''# FORWARD PLAN — {rec_type.upper()}
# Provider: {provider.upper()} | Resource: {resource_id}
# Generated by EAF Twin-Plan Engine

terraform {{
  required_providers {{
    {provider} = {{ source = "hashicorp/{provider}", version = "~> 5.0" }}
  }}
}}

# Apply optimization: {rec_type}
resource "null_resource" "eaf_{rec_type}_{resource_id.replace("-","_")}" {{
  provisioner "local-exec" {{
    command = "echo 'Applying {rec_type} on {resource_id}'"
  }}
  
  triggers = {{
    action_id = "{rec_id}"
  }}
}}

output "action" {{ value = "{rec_type}" }}
output "resource" {{ value = "{resource_id}" }}
'''
        rbk_hcl = f'''# ROLLBACK PLAN — Revert {rec_type.upper()}
# This plan reverses the forward action

terraform {{
  required_providers {{
    {provider} = {{ source = "hashicorp/{provider}", version = "~> 5.0" }}
  }}
}}

resource "null_resource" "eaf_rollback_{resource_id.replace('-','_')}" {{
  provisioner "local-exec" {{
    command = "echo 'Reverting {rec_type} on {resource_id}'"
  }}
}}

output "rollback_status" {{ value = "Reverted {rec_type}" }}
'''
        forward = TerraformPlan(
            plan_id=f"fwd-{rec_id[:8]}",
            plan_type="forward",
            provider=provider,
            resource_type="other",
            resource_id=resource_id,
            hcl_code=fwd_hcl,
            description=f"Apply {rec_type} on {resource_id}",
            estimated_duration_seconds=60,
            affects_traffic=False,
            data_mutation=False,
        )
        rollback = TerraformPlan(
            plan_id=f"rbk-{rec_id[:8]}",
            plan_type="rollback",
            provider=provider,
            resource_type="other",
            resource_id=resource_id,
            hcl_code=rbk_hcl,
            description=f"Revert {rec_type} on {resource_id}",
            estimated_duration_seconds=60,
            affects_traffic=False,
            data_mutation=False,
        )
        return ReversibilityGate(
            recommendation_id=rec_id,
            forward_plan=forward,
            rollback_plan=rollback,
            reversibility_class=ReversibilityClass.FULLY_REVERSIBLE,
            auto_apply_eligibility=AutoApplyEligibility.ELIGIBLE,
            what_is_lost_on_rollback=[],
            cost_of_reversal_inr=0.0,
            revert_time_seconds=60,
            revert_downtime_seconds=0,
            policy_validated=True,
            dry_run_passed=True,
            safety_summary="✅ FULLY REVERSIBLE — no data impact",
        )
