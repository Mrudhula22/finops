"""
Twin-Plan Terraform Generator
==============================
For every optimization recommendation, generates TWO Terraform plans:
  1. Forward plan  — applies the optimization
  2. Rollback plan — exact inverse that restores prior state

Then classifies reversibility:
  FULLY_REVERSIBLE    → auto-apply eligible
  PARTIALLY_REVERSIBLE → requires user acknowledgment of what is lost
  IRREVERSIBLE         → always requires manual approval

Also computes cost-of-reversal and downtime estimate.
"""

import logging
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Any, Dict, List, Optional

logger = logging.getLogger(__name__)


# ── Enums ──────────────────────────────────────────────────────────────────────

class ReversibilityClass(str, Enum):
    FULLY_REVERSIBLE     = "FULLY_REVERSIBLE"
    PARTIALLY_REVERSIBLE = "PARTIALLY_REVERSIBLE"
    IRREVERSIBLE         = "IRREVERSIBLE"


class AutoApplyEligibility(str, Enum):
    ELIGIBLE       = "ELIGIBLE"         # one-click auto-apply
    NEEDS_ACK      = "NEEDS_ACK"        # user must acknowledge losses
    MANUAL_ONLY    = "MANUAL_ONLY"      # always manual, regardless of confidence


# ── Data structures ────────────────────────────────────────────────────────────

@dataclass
class TerraformPlan:
    plan_id: str
    plan_type: str                      # forward | rollback
    provider: str
    resource_type: str
    resource_id: str
    hcl_code: str                       # the actual Terraform HCL
    description: str
    estimated_duration_seconds: int
    affects_traffic: bool
    data_mutation: bool                 # does this touch data / snapshots?
    generated_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())


@dataclass
class ReversibilityGate:
    recommendation_id: str
    forward_plan: TerraformPlan
    rollback_plan: TerraformPlan
    reversibility_class: ReversibilityClass
    auto_apply_eligibility: AutoApplyEligibility
    what_is_lost_on_rollback: List[str]   # e.g. ["New metrics data (last 5 min)"]
    cost_of_reversal_inr: float
    revert_time_seconds: int
    revert_downtime_seconds: int
    policy_validated: bool
    dry_run_passed: bool
    safety_summary: str                   # one-line shown to user
    validated_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())


# ── HCL Templates ─────────────────────────────────────────────────────────────

def _aws_resize_forward(resource_id: str, new_type: str, old_type: str) -> str:
    return f'''# FORWARD PLAN — AWS EC2 Rightsizing
# Resizes {resource_id} from {old_type} → {new_type}
# Generated by EAF Twin-Plan Engine

terraform {{
  required_providers {{
    aws = {{ source = "hashicorp/aws", version = "~> 5.0" }}
  }}
}}

resource "aws_instance" "target" {{
  # Reference existing instance by import:
  # terraform import aws_instance.target {resource_id}

  instance_type = "{new_type}"

  lifecycle {{
    prevent_destroy = false
    ignore_changes  = [ami, user_data]
  }}
}}

output "new_instance_type" {{
  value = aws_instance.target.instance_type
}}

output "estimated_monthly_saving_inr" {{
  value = "See recommendation card"
}}
'''


def _aws_resize_rollback(resource_id: str, old_type: str, new_type: str) -> str:
    return f'''# ROLLBACK PLAN — AWS EC2 Rightsizing Revert
# Restores {resource_id} from {new_type} → {old_type}
# EXACT INVERSE of forward plan — pre-validated by EAF

terraform {{
  required_providers {{
    aws = {{ source = "hashicorp/aws", version = "~> 5.0" }}
  }}
}}

resource "aws_instance" "target" {{
  instance_type = "{old_type}"   # ← original size restored

  lifecycle {{
    prevent_destroy = true       # safety lock on rollback
    ignore_changes  = [ami, user_data]
  }}
}}

output "rollback_complete" {{
  value = "Instance restored to {old_type}"
}}
'''


def _aws_terminate_forward(resource_id: str, instance_type: str) -> str:
    return f'''# FORWARD PLAN — Terminate Idle AWS EC2 Instance
# WARNING: IRREVERSIBLE — instance cannot be un-terminated
# Snapshot created automatically before termination

terraform {{
  required_providers {{
    aws = {{ source = "hashicorp/aws", version = "~> 5.0" }}
  }}
}}

# Step 1: Create AMI snapshot before termination
resource "aws_ami_from_instance" "backup_before_terminate" {{
  name               = "eaf-backup-{resource_id}-${{formatdate("YYYYMMDDhhmmss", timestamp())}}"
  source_instance_id = "{resource_id}"
  snapshot_without_reboot = false

  tags = {{
    Purpose   = "EAF-PreTermination-Backup"
    SourceId  = "{resource_id}"
    CreatedBy = "EAF-AutoOptimization"
  }}
}}

# Step 2: Terminate (only after snapshot confirmed)
resource "null_resource" "terminate_{resource_id.replace('-','_')}" {{
  depends_on = [aws_ami_from_instance.backup_before_terminate]

  provisioner "local-exec" {{
    command = "aws ec2 terminate-instances --instance-ids {resource_id}"
  }}
}}
'''


def _aws_terminate_rollback(resource_id: str, instance_type: str) -> str:
    return f'''# ROLLBACK PLAN — Restore Terminated Instance from AMI
# NOTE: PARTIALLY_REVERSIBLE — new instance ID will differ; 
# ephemeral data since last snapshot is lost.

terraform {{
  required_providers {{
    aws = {{ source = "hashicorp/aws", version = "~> 5.0" }}
  }}
}}

data "aws_ami" "backup" {{
  most_recent = true
  owners      = ["self"]
  filter {{
    name   = "name"
    values = ["eaf-backup-{resource_id}-*"]
  }}
}}

resource "aws_instance" "restored" {{
  ami           = data.aws_ami.backup.id
  instance_type = "{instance_type}"

  tags = {{
    Name      = "restored-{resource_id}"
    RestoredBy = "EAF-Rollback"
  }}
}}

output "restored_instance_id" {{
  value = aws_instance.restored.id
}}
output "warning" {{
  value = "New instance ID differs from original. Update DNS/load balancer targets."
}}
'''


